//! UTF-8 bitmap font rendering for the SAIOS graphics console.
//!
//! Supports extended Unicode coverage:
//! - Basic Latin (ASCII 0x20-0x7E) — generated font table
//! - Latin-1 Supplement (0xA0-0xFF) — accented letters, symbols, fractions
//! - Box drawing (single + double-line, rounded corners)
//! - Block elements and progress characters
//! - Arrows, math symbols, currency signs
//! - Greek letters, Cyrillic (subset)
//! - Common typographic symbols
//!
//! Glyph lookup uses a three-tier strategy:
//!   1. Direct index for ASCII (O(1), most common path)
//!   2. Direct index for Latin-1 Supplement (O(1))
//!   3. Binary search in the sorted Unicode overlay table (O(log n))
//!   4. Accent-stripping fallback for Latin text
//!
//! Glyphs are 8x16 pixels, stored as 16 bytes per character (one byte per row,
//! MSB = leftmost pixel).

