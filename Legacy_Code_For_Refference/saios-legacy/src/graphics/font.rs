/// Calculate the byte size needed for a UTF-8 string display.
pub fn string_width(s: &str) -> usize {
    s.chars().count() * GLYPH_W
}

/// Calculate the height needed for a wrapped string.
pub fn string_height_wrapped(s: &str, max_width: usize) -> usize {
    let chars_per_line = max_width / GLYPH_W;
    let mut lines = 1;
    let mut char_count = 0;

    for ch in s.chars() {
        if ch == '\n' {
            lines += 1;
            char_count = 0;
        } else {
            char_count += 1;
            if char_count >= chars_per_line {
                lines += 1;
                char_count = 0;
            }
        }
    }

    lines * GLYPH_H
}

/// Test whether a character has a real glyph (not a fallback).
/// Useful for diagnostics and for shells that want to count rendered width.
pub fn has_glyph(ch: char) -> bool {
    let code = ch as u32;
    ascii_glyph_index(code).is_some()
        || latin1_glyph_index(code).is_some()
        || unicode_glyph_lookup(code).is_some()
}
