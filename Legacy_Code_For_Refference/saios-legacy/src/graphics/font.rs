/// Draw a single character at pixel position (x, y) with the given foreground
/// and background colours (ARGB format). Out-of-range characters render as '?'.
///
/// This is the basic 1-bit renderer: each glyph bit is either fully on (fg)
/// or fully off (bg).  For smoother text, use `draw_char_aa` which applies
/// sub-pixel anti-aliasing.
pub fn draw_char(x: usize, y: usize, ch: char, fg: u32, bg: u32) {
    let glyph = glyph_for(ch);

    for (row, bits) in glyph.iter().enumerate() {
        for col in 0..GLYPH_W {
            // MSB is the leftmost pixel.
            let on = (bits >> (7 - col)) & 1 != 0;
            let colour = if on { fg } else { bg };
            super::vesa_put(x + col, y + row, colour);
        }
    }
}

/// Draw a single character with 2-bit anti-aliased rendering.
///
/// Instead of hard-edged 1-bit pixels, this uses the glyph as a coverage mask
/// with two intermediate levels (33%, 66%) produced by a 2×2 box filter over
/// the source glyph.  The result is smoother diagonal curves and serifs at the
/// cost of ~4× more pixel writes (still very fast for an 8×16 font).
///
/// The caller must ensure the framebuffer is active and (x, y) is in range.
pub fn draw_char_aa(x: usize, y: usize, ch: char, fg: u32, bg: u32) {
    let glyph = glyph_for(ch);

    // Pre-decompose fg and bg into channels for alpha blending.
    let fg_r = (fg >> 16) & 0xFF;
    let fg_g = (fg >> 8) & 0xFF;
    let fg_b = fg & 0xFF;
    let bg_r = (bg >> 16) & 0xFF;
    let bg_g = (bg >> 8) & 0xFF;
    let bg_b = bg & 0xFF;

    // We produce a 4×32 supersampled grid (2×2 per glyph pixel → 16×32 samples)
    // and box-filter down to the 8×16 output.  For a 1-bit source, the 2×2 block
    // coverage can be 0, 1, 2, 3, or 4 → we map to alpha 0, 64, 128, 192, 255.
    //
    // To avoid the 4× resolution explosion, we compute the 2×2 coverage per
    // *output* pixel directly from neighbouring glyph bits.  A pixel at glyph
    // column `c` and row `r` gets alpha based on the 2×2 block centered on it
    // (using the pixel itself plus its right and bottom neighbours as the 2×2
    // supersample).

    for (row, bits) in glyph.iter().enumerate() {
        let next_row_bits = if row + 1 < GLYPH_H { glyph[row + 1] } else { 0 };

        for col in 0..GLYPH_W {
            // Count "on" samples in the 2×2 block: (this_col, this_row),
            // (this_col+0.5, this_row), (this_col, this_row+0.5),
            // (this_col+0.5, this_row+0.5).
            let mut count: u32 = 0;
            // Current pixel
            if (bits >> (7 - col)) & 1 != 0 {
                count += 2;
            }
            // Right neighbour (half contribution)
            if col + 1 < GLYPH_W && (bits >> (7 - col - 1)) & 1 != 0 {
                count += 1;
            }
            // Bottom neighbour (half contribution)
            if (next_row_bits >> (7 - col)) & 1 != 0 {
                count += 1;
            }

            // Map count [0..4] → alpha [0..255].  0→0, 1→85, 2→170, 3→255, 4→255
            // (we clamp count=4 to 255, same as count=3, since 4 means fully on)
            let alpha = if count == 0 {
                0
            } else if count == 1 {
                85
            } else if count == 2 {
                170
            } else {
                255
            };

            let colour = if alpha == 255 {
                fg
            } else if alpha == 0 {
                bg
            } else {
                // Blend fg over bg
                let a = alpha;
                let inv = 255 - a;
                let r = (fg_r * a + bg_r * inv) / 255;
                let g = (fg_g * a + bg_g * inv) / 255;
                let b = (fg_b * a + bg_b * inv) / 255;
                (r << 16) | (g << 8) | b
            };
            super::vesa_put(x + col, y + row, colour);
        }
    }
}

/// Draw a string starting at (x, y) with automatic UTF-8 decoding.
/// Does not wrap — caller manages layout.
pub fn draw_string(mut x: usize, y: usize, s: &str, fg: u32, bg: u32) {
    for ch in s.chars() {
        // Handle common control characters
        match ch {
            '\n' | '\r' => continue, // Skip line breaks (caller should handle)
            '\t' => {
                // Tab = 8 spaces
                for _ in 0..8 {
                    draw_char(x, y, ' ', fg, bg);
                    x += GLYPH_W;
                }
            }
            _ => {
                draw_char(x, y, ch, fg, bg);
                x += GLYPH_W;
            }
        }
    }
}

/// Draw a string with anti-aliased rendering.  Same semantics as `draw_string`
/// but uses `draw_char_aa` for smoother glyphs.
pub fn draw_string_aa(mut x: usize, y: usize, s: &str, fg: u32, bg: u32) {
    for ch in s.chars() {
        match ch {
            '\n' | '\r' => continue,
            '\t' => {
                for _ in 0..8 {
                    draw_char_aa(x, y, ' ', fg, bg);
                    x += GLYPH_W;
                }
            }
            _ => {
                draw_char_aa(x, y, ch, fg, bg);
                x += GLYPH_W;
            }
        }
    }
}

/// Draw a string with word wrapping at a maximum width.
/// Returns the y-position after the last line.
pub fn draw_string_wrapped(
    x: usize,
    mut y: usize,
    s: &str,
    fg: u32,
    bg: u32,
    max_width: usize,
) -> usize {
    let chars_per_line = max_width / GLYPH_W;
    let mut line_start = 0;
    let last_space = 0;
    let char_count = 0;

    let chars: Vec<char> = s.chars().collect();
    let total = chars.len();

    while line_start < total {
        // Find the best break point for this line
        let end = if line_start + chars_per_line >= total {
            total
        } else {
            // Look for a space to break at
            let mut break_at = line_start + chars_per_line;
            for i in (line_start..line_start + chars_per_line).rev() {
                if chars[i] == ' ' || chars[i] == '\n' {
                    break_at = i + 1;
                    break;
                }
            }
            break_at.min(total)
        };

        // Draw this line
        let mut line_x = x;
        for ch in chars.iter().take(end).skip(line_start) {
            if *ch != '\n' {
                draw_char(line_x, y, *ch, fg, bg);
                line_x += GLYPH_W;
            }
        }

        y += GLYPH_H;
        line_start = end;

        // Skip the newline character if we broke at one
        if line_start < total && chars[line_start - 1] == '\n' {
            // Already consumed
        }
    }

    y
}

