/// Return the generated ASCII glyph index for a code point.
#[inline]
fn ascii_glyph_index(code: u32) -> Option<usize> {
    if code >= FONT_FIRST as u32 && code <= FONT_LAST as u32 {
        Some((code - FONT_FIRST as u32) as usize)
    } else {
        None
    }
}

/// Return the Latin-1 Supplement glyph index for a code point.
#[inline]
fn latin1_glyph_index(code: u32) -> Option<usize> {
    if code >= LATIN1_FIRST as u32 && code <= LATIN1_LAST as u32 {
        Some((code - LATIN1_FIRST as u32) as usize)
    } else {
        None
    }
}

/// Binary search for a code point in the sorted UNICODE_GLYPHS table.
/// Returns a reference to the glyph, or `None` if not found.
fn unicode_glyph_lookup(code: u32) -> Option<&'static Glyph> {
    let mut lo = 0usize;
    let mut hi = UNICODE_GLYPHS.len();
    while lo < hi {
        let mid = lo + (hi - lo) / 2;
        let (cp, glyph) = &UNICODE_GLYPHS[mid];
        match cp.cmp(&code) {
            core::cmp::Ordering::Equal => return Some(glyph),
            core::cmp::Ordering::Less => lo = mid + 1,
            core::cmp::Ordering::Greater => hi = mid,
        }
    }
    None
}

/// Map accented Latin and typographic punctuation to an ASCII base glyph.
///
/// This is not full Unicode normalization. It is a pragmatic kernel-console
/// fallback so common UTF-8 text stays readable when the exact glyph is not
/// available.  The Latin-1 Supplement table (0xA0-0xFF) already renders these
/// natively; this fallback covers characters outside that range (e.g. 0x0100+
/// Latin Extended-A).
fn latin_fallback(ch: char) -> Option<char> {
    match ch {
        '\u{00A0}' => Some(' '),
        // Dashes → hyphen
        '\u{2010}' | '\u{2011}' | '\u{2012}' | '\u{2013}' | '\u{2014}' | '\u{2212}' => Some('-'),
        // Quotation marks
        '\u{2018}' | '\u{2019}' | '\u{201A}' | '\u{201B}' => Some('\''),
        '\u{201C}' | '\u{201D}' | '\u{201E}' | '\u{201F}' => Some('"'),
        // Latin Extended-A / Extended-B accents → strip to base ASCII
        '\u{0100}'..='\u{0105}' => Some('a'), // Ā-å
        '\u{0106}'..='\u{010D}' => Some('c'), // Ć-č
        '\u{010E}'..='\u{0111}' => Some('d'), // Ď-đ
        '\u{0112}'..='\u{011B}' => Some('e'), // Ē-ě
        '\u{011C}'..='\u{0123}' => Some('g'), // Ĝ-ģ
        '\u{0124}'..='\u{0127}' => Some('h'), // Ĥ-ħ
        '\u{0128}'..='\u{0131}' => Some('i'), // Ĩ-ı
        '\u{0134}'..='\u{0135}' => Some('j'), // Ĵ-ĵ
        '\u{0136}'..='\u{0137}' => Some('k'), // Ķ-ķ
        '\u{0139}'..='\u{0142}' => Some('l'), // Ĺ-ł
        '\u{0143}'..='\u{014B}' => Some('n'), // Ń-ŋ
        '\u{014C}'..='\u{0151}' => Some('o'), // Ō-ő
        '\u{0152}' | '\u{0153}' => Some('o'), // Œ-œ
        '\u{0154}'..='\u{0159}' => Some('r'), // Ŕ-ř
        '\u{015A}'..='\u{0161}' => Some('s'), // Ś-ś
        '\u{0162}'..='\u{0167}' => Some('t'), // Ţ-ţ
        '\u{0168}'..='\u{0173}' => Some('u'), // Ũ-ű
        '\u{0174}'..='\u{0175}' => Some('w'), // Ŵ-ŵ
        '\u{0176}'..='\u{0177}' => Some('y'), // Ŷ-ŷ
        '\u{0178}' => Some('y'),              // Ÿ
        '\u{0179}'..='\u{017E}' => Some('z'), // Ź-ž
        // Latin-1 Supplement (for safety if somehow not in the Latin-1 table)
        '\u{00C0}'..='\u{00C5}' | '\u{00E0}'..='\u{00E5}' => Some('a'),
        '\u{00C7}' | '\u{00E7}' => Some('c'),
        '\u{00C8}'..='\u{00CB}' | '\u{00E8}'..='\u{00EB}' => Some('e'),
        '\u{00CC}'..='\u{00CF}' | '\u{00EC}'..='\u{00EF}' => Some('i'),
        '\u{00D1}' | '\u{00F1}' => Some('n'),
        '\u{00D2}'..='\u{00D6}' | '\u{00D8}' | '\u{00F2}'..='\u{00F6}' | '\u{00F8}' => Some('o'),
        '\u{00D9}'..='\u{00DC}' | '\u{00F9}'..='\u{00FC}' => Some('u'),
        '\u{00DD}' | '\u{00FD}' | '\u{00FF}' => Some('y'),
        '\u{00C6}' | '\u{00E6}' => Some('a'),
        '\u{00DE}' | '\u{00FE}' => Some('p'),
        '\u{00DF}' => Some('s'),
        _ => None,
    }
}

/// Resolve one Unicode scalar value to a kernel glyph.
///
/// Lookup order (fastest to slowest):
///   1. ASCII direct index        — O(1), covers most kernel text
///   2. Latin-1 Supplement index   — O(1), covers accented letters + symbols
///   3. Unicode overlay binary search — O(log n), covers box drawing, math, etc.
///   4. Accent-stripping fallback  — returns readable ASCII base
///   5. Replacement character     — U+FFFD glyph or '?'
fn glyph_for(ch: char) -> &'static Glyph {
    let code = ch as u32;

    // Tier 1: ASCII — the hot path for >90% of kernel text.
    if let Some(idx) = ascii_glyph_index(code) {
        return unsafe { FONT.get_unchecked(idx) };
    }

    // Tier 2: Latin-1 Supplement — accented letters, symbols, fractions.
    if let Some(idx) = latin1_glyph_index(code) {
        return unsafe { LATIN1_FONT.get_unchecked(idx) };
    }

    // Tier 3: Binary search in the Unicode overlay table.
    if let Some(glyph) = unicode_glyph_lookup(code) {
        return glyph;
    }

    // Tier 4: Readable fallback for Latin text (strips accent marks).
    if let Some(base) = latin_fallback(ch)
        && let Some(idx) = ascii_glyph_index(base as u32)
    {
        return unsafe { FONT.get_unchecked(idx) };
    }

    // Tier 5: Replacement character (U+FFFD), or ASCII '?' as last resort.
    if let Some(glyph) = unicode_glyph_lookup(0xFFFD) {
        return glyph;
    }
    unsafe { FONT.get_unchecked(ascii_glyph_index('?' as u32).unwrap_or(0)) }
}

