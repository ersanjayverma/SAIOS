/// Last ASCII code point in the font (0x7E = '~')
const FONT_LAST: u8 = 0x7E;

/// One fixed-size 8x16 glyph.
///
/// The kernel font deliberately uses a tiny byte format instead of a TTF/PSF
/// parser: each byte is one scanline and bit 7 is the leftmost pixel. That keeps
/// text rendering available during early boot and fault handling.
