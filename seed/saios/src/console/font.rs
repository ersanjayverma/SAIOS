pub fn glyph(c: char) -> &'static [u8; 16] {
    match c {
        ' ' => &GLYPH_SPACE,
        '!' => &GLYPH_EXCLAMATION,
        ',' => &GLYPH_COMMA,
        '-' => &GLYPH_DASH,
        '.' => &GLYPH_DOT,
        ':' => &GLYPH_COLON,
        '0' => &GLYPH_ZERO,
        '1' => &GLYPH_ONE,
        '2' => &GLYPH_TWO,
        '3' => &GLYPH_THREE,
        '4' => &GLYPH_FOUR,
        '5' => &GLYPH_FIVE,
        '6' => &GLYPH_SIX,
        '7' => &GLYPH_SEVEN,
        '8' => &GLYPH_EIGHT,
        '9' => &GLYPH_NINE,
        'A'..='Z' => &GLYPH_UPPER[(c as u8 - b'A') as usize],
        'a'..='z' => &GLYPH_LOWER[(c as u8 - b'a') as usize],
        _ => &GLYPH_UNKNOWN,
    }
}
